/* 输入归一化：去首尾空白、全角转半角；keepDigits 时只留数字 */
GLN.norm = function(s, keepDigits){
  s = String(s||"").trim();
  s = s.replace(/[\uFF01-\uFF5E]/g, ch => String.fromCharCode(ch.charCodeAt(0)-0xFEE0));
  s = s.replace(/\u3000/g, " ");
  if(keepDigits) s = s.replace(/\D/g, "");
  return s;
};

/* djb2 哈希（32-bit） */
GLN._djb2 = function(str){
  let h = 5381;
  for(let i=0;i<str.length;i++) h = ((h*33) + str.charCodeAt(i)) >>> 0;
  return h.toString(16).padStart(8,"0");
};

/* SHA-256 十六进制小写；file:// 无 crypto.subtle 时降级 */
GLN._useSha = !!(window.crypto && crypto.subtle);
if(!GLN._useSha) console.log("%c校验已降级。", "color:#999");

GLN.sha256 = async function(str){
  if(GLN._useSha){
    const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(str));
    return [...new Uint8Array(buf)].map(b=>b.toString(16).padStart(2,"0")).join("");
  }
  return GLN._djb2(str);
};

/* 统一校验：await GLN.verify("motto", 输入) -> bool */
GLN.verify = async function(key, raw, keepDigits){
  const h = GLN.HASH[key];
  if(!h) return false;
  const normed = GLN.norm(raw, keepDigits);
  if(!normed) return false;
  const digest = await GLN.sha256(normed);
  return digest === (GLN._useSha ? h.sha : h.djb2);
};

